void SK6812_Handle(uint32_t R8G8B8)
{
	int8_t   i,tp;
	uint32_t G8R8B8;
	
	G8R8B8 = ((R8G8B8 & 0x00ff00) << 8) + ((R8G8B8 & 0xff0000) >> 8) + (R8G8B8 & 0x0000ff);


	for(i=23;i>=0;i--)
	{
		tp = (G8R8B8 >> i) & 0x01;
		if(tp == 1)
		{
			SK6812_Set_1();
		}
		else
		{
			SK6812_Set_0();
		}
	}
}

