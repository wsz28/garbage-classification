void SK6812_Init(void)
{
	rcu_periph_clock_enable(SK6812_PORT_RTC);
	
	gpio_mode_set(SK6812_PORT, GPIO_MODE_OUTPUT, GPIO_PUPD_PULLDOWN, SK6812_PORT_PIN);
	
	gpio_output_options_set(SK6812_PORT, GPIO_OTYPE_PP, GPIO_OSPEED_200MHZ, SK6812_PORT_PIN);
	
	gpio_bit_write(SK6812_PORT, SK6812_PORT_PIN, RESET);
	
	SK6812_Reset();
}


